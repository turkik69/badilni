const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const read = name => fs.readFileSync(path.join(root, name), 'utf8');
const memory = new Map();
const document = {documentElement:{lang:'',dir:''},title:''};
const window = {document,localStorage:{getItem:key=>memory.get(key)||null,setItem:(key,value)=>memory.set(key,value)}};
vm.runInNewContext(read('i18n.js'), {window});
const i18n=window.BadilniI18n;
assert.equal(i18n.language,'ar');
assert.equal(document.documentElement.dir,'rtl');
assert.equal(i18n.translate('الرئيسية'),'الرئيسية');
i18n.setLanguage('en');
assert.equal(memory.get('badilni-language'),'en');
assert.equal(document.documentElement.lang,'en');
assert.equal(document.documentElement.dir,'ltr');
assert.equal(i18n.translate('تقديم عرض مبادلة'),'Make a swap offer');
assert.equal(i18n.translate('مطابقات جديدة (4)'),'new matches (4)');
assert.equal(i18n.translate('3 غرض للمبادلة'),'3 items for swap');
assert.equal(i18n.translate('تعذّر رفع الصورة: network'),'Could not upload photo: network');
assert.equal(i18n.translate('هاتف أحمد'),'هاتف أحمد','user content must not be translated');
i18n.setLanguage('ar');
assert.equal(document.documentElement.dir,'rtl');
const html=read('index.html');
assert.match(html, /src="i18n\.js\?v=/);
assert.match(html, /data-language-toggle/);
assert.match(html, /BadilniI18n\.apply\(frame\)/);
assert.match(read('scripts/build-web.mjs'), /'i18n\.js'/);
assert.match(read('sw.js'), /'\.\/i18n\.js'/);
const gradle=read('android/app/build.gradle');
assert.match(gradle, /BADILNI_UPLOAD_KEYSTORE/);
assert.match(gradle, /signingConfig signingConfigs\.upload/);
assert.match(read('ios/App/App.xcodeproj/project.pbxproj'), /com\.apple\.Push/);
assert.match(read('ios/App/App.xcodeproj/project.pbxproj'), /CODE_SIGN_ENTITLEMENTS = App\/App\.entitlements/);
assert.match(read('ios/App/App/App.entitlements'), /aps-environment/);
console.log('✓ language switch, content mapping, offline assets and native release wiring passed');
